import json
from pathlib import Path
from typing import Any

from comfyshop_api.main import create_app
from comfyshop_api.schemas import MEDIA_INPUT_KINDS
from comfyshop_api.services.asset_formats import asset_content_types

ROOT = Path(__file__).resolve().parent.parent
SKILL_CONTRACT_START = "# BEGIN GENERATED API CONTRACT"
SKILL_CONTRACT_END = "# END GENERATED API CONTRACT"


def array_parameter(schema: dict[str, Any]) -> bool:
    return schema.get("type") == "array" or any(
        array_parameter(alternative) for alternative in schema.get("anyOf", ())
    )


def write_skill_contract(openapi: dict[str, Any], categories: list[str]) -> None:
    skill = ROOT / "integrations/skills/comfyshop"
    aliases = json.loads((skill / "operations.json").read_text())
    endpoints = {
        operation["operationId"]: (method.upper(), path.removeprefix("/api/v1"), operation)
        for path, methods in openapi["paths"].items()
        for method, operation in methods.items()
        if "operationId" in operation
    }
    lines = [f"WORKFLOW_CATEGORIES = {tuple(categories)!r}", "", "OPERATIONS = {"]
    for alias, definition in aliases.items():
        operation_id, output = (
            (definition, "json")
            if isinstance(definition, str)
            else (definition["id"], definition["output"])
        )
        method, path, operation = endpoints[operation_id]
        query = [item for item in operation.get("parameters", ()) if item["in"] == "query"]
        body = operation.get("requestBody", {})
        filters = tuple(item["name"] for item in query)
        repeatable = tuple(item["name"] for item in query if array_parameter(item["schema"]))
        arguments = [repr(method), repr(path)]
        if filters:
            arguments.append(repr(filters))
        if body.get("required"):
            arguments.append("payload=True")
        if output != "json":
            arguments.append(f"output={output!r}")
        if "application/octet-stream" in body.get("content", {}):
            arguments.append("binary=True")
        if repeatable:
            arguments.append(f"repeatable_filters={repeatable!r}")
        lines.append(f"    {alias!r}: Operation({', '.join(arguments)}),")
    lines.append("}")
    script = skill / "scripts/comfyshop.py"
    prefix, generated = script.read_text().split(SKILL_CONTRACT_START, 1)
    _, suffix = generated.split(SKILL_CONTRACT_END, 1)
    script.write_text(
        f"{prefix}{SKILL_CONTRACT_START}\n" + "\n".join(lines) + f"\n{SKILL_CONTRACT_END}{suffix}"
    )


def export() -> None:
    client = ROOT / "packages/api-client"
    openapi = create_app().openapi()
    categories = openapi["components"]["schemas"]["WorkflowCategory"]["enum"]
    (client / "openapi.json").write_text(json.dumps(openapi, ensure_ascii=False, indent=2) + "\n")
    default_asset_formats = {kind: asset_content_types([kind]) for kind in MEDIA_INPUT_KINDS}
    (client / "src/runtime-contract.ts").write_text(
        "// Generated by pnpm api:generate.\n"
        f"export const defaultAssetContentTypes = {json.dumps(default_asset_formats)} as const;\n"
        f"export const workflowCategoryValues = {json.dumps(categories)} as const;\n"
    )
    write_skill_contract(openapi, categories)


if __name__ == "__main__":
    export()
